#include <iostream>
using namespace std;

int main()
{
    int value=50;
    cout << value << endl;

    value+=10;
    cout << value << endl;

    value-=10;
    cout << value << endl;

    value*=10;
    cout << value << endl;

    value/=10;
    cout << value << endl;

    value%=6;
    cout << value << endl;
    return 0;
}